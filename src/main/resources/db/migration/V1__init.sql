create table company (
  id bigint generated by default as identity primary key,
  name varchar(200) not null,
  platform varchar(40) not null,
  board_token varchar(200),
  careers_url varchar(1000),
  enabled boolean not null default true,
  last_sync_at timestamp with time zone
);
create table job (
  id bigint generated by default as identity primary key,
  company_id bigint not null references company(id) on delete cascade,
  external_id varchar(300) not null,
  title varchar(500),
  location varchar(500),
  url varchar(1500),
  description text,
  posted_at timestamp with time zone,
  discovered_at timestamp with time zone,
  match_score int not null default 0,
  matched boolean not null default false,
  constraint uq_job_company_external unique (company_id, external_id)
);
create index idx_job_discovered on job(discovered_at desc);
create table schedule_run (
  id bigint generated by default as identity primary key,
  trigger_type varchar(20),
  started_at timestamp with time zone,
  finished_at timestamp with time zone,
  status varchar(20),
  companies_scanned int not null default 0,
  jobs_found int not null default 0,
  new_jobs int not null default 0,
  matched_jobs int not null default 0,
  duplicates int not null default 0,
  failures int not null default 0,
  log text
);
create table profile (
  id bigint primary key,
  full_name varchar(200), email varchar(200), phone varchar(50),
  experience_years int not null default 5,
  skills varchar(2000), locations varchar(1000), roles varchar(1000), expected_ctc varchar(100),
  notice_period_days int not null default 30,
  min_match_score int not null default 60,
  resume_url varchar(1000), resume_file_name varchar(300),
  default_portal_username varchar(200), default_portal_email varchar(200),
  default_portal_password_enc varchar(1000)
);
